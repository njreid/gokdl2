package parser

import (
	"errors"
	"fmt"

	"github.com/njreid/gokdl2/document"
	"github.com/njreid/gokdl2/internal/tokenizer"
)

func tokensAdjacent(prev, curr tokenizer.Token) bool {
	if prev.Line != curr.Line {
		return false
	}
	return curr.Column == prev.Column+len(prev.Data)
}

func isValueLikeToken(id tokenizer.TokenID) bool {
	switch id {
	case tokenizer.BareIdentifier, tokenizer.RawString, tokenizer.QuotedString, tokenizer.ExpressionString,
		tokenizer.Decimal, tokenizer.Hexadecimal, tokenizer.Octal, tokenizer.Binary,
		tokenizer.SuffixedDecimal, tokenizer.Boolean, tokenizer.Null, tokenizer.Keyword,
		tokenizer.BraceClose:
		return true
	default:
		return false
	}
}

func requiresV2Separation(prev, curr tokenizer.Token) bool {
	if !tokensAdjacent(prev, curr) {
		return false
	}

	if isValueLikeToken(prev.ID) {
		switch curr.ID {
		case tokenizer.BareIdentifier, tokenizer.RawString, tokenizer.QuotedString, tokenizer.ExpressionString,
			tokenizer.Decimal, tokenizer.Hexadecimal, tokenizer.Octal, tokenizer.Binary,
			tokenizer.SuffixedDecimal, tokenizer.Boolean, tokenizer.Null, tokenizer.Keyword,
			tokenizer.ParensOpen:
			return true
		}
	}

	if prev.ID == tokenizer.ParensClose && curr.ID == tokenizer.TokenComment {
		return true
	}

	return false
}

func isTriviaToken(id tokenizer.TokenID) bool {
	switch id {
	case tokenizer.Whitespace, tokenizer.Newline, tokenizer.SingleLineComment, tokenizer.MultiLineComment:
		return true
	default:
		return false
	}
}

type Parser struct {
}

// New creates a new Parser
func New() *Parser {
	return &Parser{}
}

// NewContext creates a new ParseContext
func (p *Parser) NewContext() *ParseContext {
	return p.NewContextOptions(defaultParseContextOptions)
}

func (p *Parser) NewContextOptions(opts ParseContextOptions) *ParseContext {
	doc := document.New()
	alloc := document.NewAllocator(opts.InputSizeEstimate / 25)
	c := &ParseContext{
		doc:   doc,
		alloc: alloc,
		opts:  opts,
	}
	if opts.Flags.Has(ParseComments) {
		c.comments = true
		c.prevEnd = -1
		c.atLineStart = true
	}
	return c
}

var eofToken = tokenizer.Token{
	ID:   tokenizer.EOF,
	Data: []byte{},
}

func (p *Parser) tokenContext(context []tokenizer.Token, idx int) string {
	if len(context) == 0 {
		return ""
	}
	start := idx - 5
	if start < 0 {
		start = 0
	}
	end := start + 10
	if end > len(context) {
		end = len(context)
	}
	b := make([]byte, 0, 128)
	b = append(b, "..."...)
	caretOffset := 3
	for i := start; i < end; i++ {
		for _, c := range context[i].Data {
			if c == '\t' || c == '\r' || c == '\n' {
				c = ' '
			}
			b = append(b, c)
		}
		if i < idx {
			caretOffset += len(context[i].Data)
		}
	}
	b = append(b, "..."...)
	b = append(b, '\n')
	for i := 0; i < caretOffset; i++ {
		b = append(b, ' ')
	}
	b = append(b, '^')
	return string(b)
}

func (p *Parser) annotatedError(err error, t tokenizer.Token, context []tokenizer.Token, contextIndex int) error {
	return fmt.Errorf("parse failed: %w at line %d, column %d\n%s", err, t.Line+1, t.Column+1, p.tokenContext(context, contextIndex))
}

// Parse parses a single token (usually generated by tokenizer.Scanner) into the given context, and returns a non-nil
// error on failure
func (p *Parser) parse(c *ParseContext, token tokenizer.Token) error {
	if c.opts.Version == tokenizer.VersionV2 {
		// The current token was just added to the ring buffer, so the previous one sits just before head. Slots that
		// have never been written have ID Unknown.
		r := &c.recent
		prev := &r.tokens[(r.head+recentTokensCount-1)%recentTokensCount]
		if prev.ID != tokenizer.Unknown && requiresV2Separation(*prev, token) {
			return missingSeparatorError(token)
		}
	}
	if c.afterIgnoredChildBlock {
		switch token.ID {
		case tokenizer.Whitespace, tokenizer.SingleLineComment, tokenizer.MultiLineComment:
		case tokenizer.TokenComment:
			// v2 allows further slashdashed child blocks after an ignored one; the state that follows still has to
			// see a child block, so the flag stays set until a real block, a newline or the end of input
			if c.opts.Version != tokenizer.VersionV2 {
				return unexpectedAfterIgnoredChildBlock(token)
			}
		case tokenizer.BraceOpen:
			// v2: ignored child blocks may precede the node's one real child block
			if c.opts.Version != tokenizer.VersionV2 || c.realBlockClosed == c.currentNode() {
				return unexpectedAfterIgnoredChildBlock(token)
			}
			c.afterIgnoredChildBlock = false
		case tokenizer.Newline, tokenizer.EOF, tokenizer.Continuation:
			if token.ID == tokenizer.Newline || token.ID == tokenizer.EOF || token.ID == tokenizer.Continuation {
				c.afterIgnoredChildBlock = false
			}
		default:
			return unexpectedAfterIgnoredChildBlock(token)
		}
	}

	if c.continuation {
		switch token.ID {
		case tokenizer.Newline:
			if c.continuationNewlineSeen {
				c.stopContinuation()
			} else {
				c.continuationNewlineSeen = true
			}
		case tokenizer.Whitespace, tokenizer.SingleLineComment, tokenizer.MultiLineComment:
			// continue waiting for the first token of the next (continued) line
		default:
			// this is the first token of the next (continued) line
			c.stopContinuation()
			c.justContinuedLine = true
		}
	} else if !isTriviaToken(token.ID) {
		c.justContinuedLine = false
	}

	handler := lookupTransition(c.state, token.ID)

	var err error
	if handler == nil {
		err = unexpectedToken(c, token)
	} else {
		err = handler(c, token)
	}

	return err
}

func (p *Parser) Parse(c *ParseContext, token tokenizer.Token) error {
	c.recent.Add(token)
	err := p.parse(c, token)
	if c.comments && err != ErrReenterState {
		c.afterToken(token)
		if err == nil && token.ID == tokenizer.EOF {
			// the end of the document may also have ended a node, so it is not enough to look for it in stateDocument
			if c.capKind != capNone {
				// a slash-dash that nothing follows, or one whose item the end of input cut short
				kind, owner := c.capKind, c.capOwner
				c.endCapture(false, token)
				if kind != capNode {
					c.flushTrailing(owner)
				}
			}
			c.flushEOF()
		}
	}
	return err
}

// ParseAll parses a slice of tokens and returns the resulting Document, or a non-nil error on failure
func (p *Parser) ParseAll(tokens []tokenizer.Token) (*document.Document, error) {
	c := p.NewContext()
	return p.ParseAllContext(c, tokens)
}

var ErrReenterState = fmt.Errorf("reenter state")

// Finish reports an error if the document ended in the middle of a construct: an unclosed child block, or a
// node-level slashdash with no node after it. It must be called after the EOF token has been parsed. The error is a
// *PosError carrying the position of the offending '{' or '/-'.
func (p *Parser) Finish(c *ParseContext) error {
	if len(c.braces) > 0 {
		open := c.braces[len(c.braces)-1]
		return errorAt(open, errors.New("unclosed child block: unexpected end of input; expected '}'"))
	}
	if c.ignoreNextNode {
		return errorAt(c.slashdash, errors.New("unexpected end of input after '/-'; expected a node"))
	}
	return nil
}

// ParseAllContext parses a slice of tokens using the given context and returns the resulting Document, or a non-nil
// error on failure
func (p *Parser) ParseAllContext(c *ParseContext, tokens []tokenizer.Token) (*document.Document, error) {
	for i := 0; i < len(tokens); i++ {
		t := tokens[i]
		if err := p.Parse(c, t); err != nil {
			if err == ErrReenterState {
				i--
				continue
			}
			return nil, p.annotatedError(err, t, tokens, i)
		}
	}

	eof := eofToken

	if len(tokens) > 0 {
		lastToken := tokens[len(tokens)-1]
		eof.Line = lastToken.Line
		eof.Column = lastToken.Column + len(lastToken.Data)
	}

	if err := p.Parse(c, eof); err != nil {
		return nil, p.annotatedError(err, eof, tokens, len(tokens)-1)
	}
	if err := p.Finish(c); err != nil {
		return nil, p.annotatedError(err, eof, tokens, len(tokens)-1)
	}

	c.doc.Version = int(c.opts.Version)
	return c.doc, nil
}
